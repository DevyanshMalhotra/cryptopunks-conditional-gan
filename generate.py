"""Generate one image using a previously trained conditional GAN snapshot."""

import argparse
import csv
import sys
from pathlib import Path

from PIL import Image


def load_attribute_names(path: Path) -> list[str]:
    with path.open(newline="", encoding="utf-8") as source:
        header = next(csv.reader(source))
    if header[:2] != ["punk_id", "filename"]:
        raise ValueError("Expected the attributes CSV generated by prepare_dataset.py")
    return header[2:]


def generate(
    upstream: Path,
    snapshot: Path,
    attributes_csv: Path,
    selected: list[str],
    output: Path,
    seed: int,
    truncation: float,
) -> None:
    if not upstream.is_dir():
        raise FileNotFoundError(f"StyleGAN3 checkout not found: {upstream}")
    if not snapshot.is_file():
        raise FileNotFoundError(f"Training snapshot not found: {snapshot}")

    # The upstream repository provides the model-loading implementation.
    sys.path.insert(0, str(upstream.resolve()))
    import dnnlib
    import legacy
    import numpy as np
    import torch

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    with dnnlib.util.open_url(str(snapshot.resolve())) as checkpoint:
        generator = legacy.load_network_pkl(checkpoint)["G_ema"].to(device).eval()

    attribute_names = load_attribute_names(attributes_csv)
    if generator.c_dim != len(attribute_names):
        raise ValueError(
            f"Snapshot expects {generator.c_dim} conditioning values; "
            f"CSV defines {len(attribute_names)}. Use the attributes.csv from training."
        )

    conditioning = torch.zeros((1, generator.c_dim), device=device)
    for name in selected:
        if name not in attribute_names:
            raise ValueError(f"Unknown attribute: {name!r}")
        conditioning[0, attribute_names.index(name)] = 1

    random_state = np.random.RandomState(seed)
    latent = torch.from_numpy(random_state.randn(1, generator.z_dim)).float().to(device)
    with torch.no_grad():
        generated = generator(latent, conditioning, truncation_psi=truncation, noise_mode="const")

    pixels = (
        (generated * 127.5 + 128).clamp(0, 255)
        .to(torch.uint8)[0].permute(1, 2, 0).cpu().numpy()
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(pixels, mode="RGB").resize((24, 24), Image.Resampling.NEAREST).save(output)
    print(f"Saved {output}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, default=Path("stylegan3"))
    parser.add_argument("--snapshot", type=Path, required=True)
    parser.add_argument("--attributes-csv", type=Path, default=Path("attributes.csv"))
    parser.add_argument("--attribute", action="append", default=[], help="Repeat to select multiple attributes")
    parser.add_argument("--output", type=Path, default=Path("generated.png"))
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--truncation", type=float, default=0.7)
    args = parser.parse_args()
    generate(args.upstream, args.snapshot, args.attributes_csv, args.attribute,
             args.output, args.seed, args.truncation)


if __name__ == "__main__":
    main()
